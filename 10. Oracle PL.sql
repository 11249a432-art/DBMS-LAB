10. Create a Trigger for Patient Audit
  
CREATE OR REPLACE TRIGGER trg_patient_audit
AFTER INSERT OR UPDATE OR DELETE ON patients
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        INSERT INTO patient_audit
            (patient_id, action_name)
        VALUES
            (:NEW.patient_id, 'INSERT');

    ELSIF UPDATING THEN
        INSERT INTO patient_audit
            (patient_id, action_name)
        VALUES
            (:NEW.patient_id, 'UPDATE');

    ELSIF DELETING THEN
        INSERT INTO patient_audit
            (patient_id, action_name)
        VALUES
            (:OLD.patient_id, 'DELETE');
    END IF;
END;
/

Output:
Trigger created.

