5. Execute a PL/SQL Block with IF-ELSE and Exception Handling
  
DECLARE
    v_name patients.patient_name%TYPE;
    v_due patients.amount_due%TYPE;
BEGIN
    SELECT patient_name, amount_due
    INTO v_name, v_due
    FROM patients
    WHERE patient_id = 1;

    IF v_due > 0 THEN
        DBMS_OUTPUT.PUT_LINE(
            v_name || ' has an outstanding balance of ' ||
            TO_CHAR(v_due)
        );
    ELSE
        DBMS_OUTPUT.PUT_LINE(
            v_name || ' has no outstanding balance'
        );
    END IF;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('Patient not found');
END;
/

Output:
Arun has an outstanding balance of 1250

PL/SQL procedure successfully completed.

6. Create a Stored Procedure to Update Patient Balance
  
CREATE OR REPLACE PROCEDURE update_patient_due(
    p_id NUMBER,
    p_amount NUMBER
)
AS
BEGIN
    UPDATE patients
    SET amount_due = p_amount
    WHERE patient_id = p_id;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(
            -20001, 'Patient not found'
        );
    END IF;
END;
/

Output:
Procedure created.

