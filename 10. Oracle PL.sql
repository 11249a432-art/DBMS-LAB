8. Create a Function to Retrieve Patient Balance
  
CREATE OR REPLACE FUNCTION get_patient_due(
    p_id NUMBER
)
RETURN NUMBER
AS
    v_due NUMBER(10,2);
BEGIN
    SELECT amount_due
    INTO v_due
    FROM patients
    WHERE patient_id = p_id;

    RETURN v_due;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN NULL;
END;
/

Output:
Function created.

