12. Execute an Explicit Cursor
  
DECLARE
    CURSOR c_due IS
        SELECT patient_name, amount_due
        FROM patients
        WHERE amount_due > 0
        ORDER BY patient_id;

    v_name patients.patient_name%TYPE;
    v_due patients.amount_due%TYPE;
BEGIN
    OPEN c_due;

    LOOP
        FETCH c_due INTO v_name, v_due;

        EXIT WHEN c_due%NOTFOUND;

        DBMS_OUTPUT.PUT_LINE(
            v_name || ': ' || TO_CHAR(v_due)
        );
    END LOOP;

    CLOSE c_due;
END;
/

Output:
Arun: 1600

PL/SQL procedure successfully completed.

